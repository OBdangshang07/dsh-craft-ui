import assert from 'node:assert/strict'
import { withCanaryBrowser, delay } from './canary-browser.mjs'

const log = process.argv[2]
if (!log || !log.includes('workbench-canary')) throw new Error('Use only the isolated workbench-canary startup log')
await withCanaryBrowser(log, async b => {
  const { evaluate, call, clickText, waitFor, capture, errors } = b
  await call('Page.bringToFront')
  await evaluate(`([...document.querySelectorAll('button')].find(b=>b.textContent.trim()==='继续'))?.click()`)
  const row = '[data-row-key="session:c8cd6e4e-38ab-49f9-b12e-a562d8f02721"]'
  await waitFor(`!!document.querySelector(${JSON.stringify(row)})`)
  await evaluate(`document.querySelector(${JSON.stringify(row)}).click()`)
  await waitFor(`!!document.querySelector('.craft-model-trigger')`)
  await evaluate(`document.querySelector('.craft-model-trigger').click()`)
  await waitFor(`!!document.querySelector('.craft-effort-slider input:not(:disabled)')`)
  assert.equal(await evaluate(`getComputedStyle(document.querySelector('.craft-effort-labels [aria-pressed="true"]')).backgroundColor`), 'rgb(48, 55, 45)')
  const compact = await evaluate(`(()=>{const panel=document.querySelector('.craft-reasoning-popup'),model=panel.querySelector('.craft-reasoning-model'),r=panel.getBoundingClientRect();return{width:r.width,height:r.height,modelFirst:panel.firstElementChild.contains(model),action:model.querySelector('.craft-model-change')?.textContent.trim(),border:getComputedStyle(model).borderTopWidth}})()`)
  assert.ok(compact.width <= 288 && compact.height <= 176, 'The default four-level popup must stay compact')
  assert.equal(compact.modelFirst, true, 'Model switching must be the first visible action')
  assert.equal(compact.action, '切换 ▾')
  assert.equal(compact.border, '2px', 'Model switching must look like a button, not a caption')
  const labels = await evaluate(`[...document.querySelectorAll('.craft-effort-labels button')].map(e=>e.textContent)`)
  assert.deepEqual(labels, ['Off', 'Low', 'High', 'Max'])
  const initial = await evaluate(`document.querySelector('.craft-effort-slider input').value`)
  const key = async (type, name, code) => call('Input.dispatchKeyEvent', { type, key: name, code: name, windowsVirtualKeyCode: code })
  await evaluate(`document.querySelector('.craft-effort-slider input').focus()`)
  await key('keyDown', 'End', 35)
  assert.match(await evaluate(`document.querySelector('.craft-reasoning-heading strong').textContent`), /Max/)
  await key('keyUp', 'End', 35)
  await waitFor(`document.querySelector('.craft-model-effort')?.textContent==='Max'`)
  await waitFor(`!!document.querySelector('.craft-effort-slider input:not(:disabled)')`)
  await waitFor(`document.activeElement===document.querySelector('.craft-effort-slider input')`)
  await capture('reasoning-slider-night')
  await capture('reasoning-compact-night-detail', '.craft-reasoning-popup')
  // Real pointer gesture: hover the native thumb, then drag through a midpoint.
  const box = await evaluate(`(()=>{const r=document.querySelector('.craft-effort-slider input').getBoundingClientRect();return{x:r.x,y:r.y,w:r.width,h:r.height}})()`)
  await call('Input.dispatchMouseEvent', { type: 'mouseMoved', x: box.x + box.w - 12, y: box.y + box.h / 2 })
  await call('Input.dispatchMouseEvent', { type: 'mousePressed', button: 'left', buttons: 1, clickCount: 1, x: box.x + box.w - 12, y: box.y + box.h / 2 })
  await call('Input.dispatchMouseEvent', { type: 'mouseMoved', button: 'left', buttons: 1, x: box.x + box.w / 2, y: box.y + box.h / 2 })
  await call('Input.dispatchMouseEvent', { type: 'mouseMoved', button: 'left', buttons: 1, x: box.x + 12, y: box.y + box.h / 2 })
  await delay(100)
  assert.equal(await evaluate(`document.querySelector('.craft-effort-slider input').value`), '0')
  assert.equal(await evaluate(`document.querySelector('.craft-model-effort').textContent`), 'Max', 'Drag preview must not write before release')
  await call('Input.dispatchMouseEvent', { type: 'mouseReleased', button: 'left', buttons: 0, clickCount: 1, x: box.x + 12, y: box.y + box.h / 2 })
  await waitFor(`document.querySelector('.craft-model-effort')?.textContent==='Off'`)
  await waitFor(`!!document.querySelector('.craft-effort-slider input:not(:disabled)')`)
  await call('Page.reload', { ignoreCache: true })
  await waitFor(`document.querySelector('.craft-model-effort')?.textContent==='Off'`)
  await evaluate(`document.querySelector('.craft-model-trigger').click()`)
  await waitFor(`!!document.querySelector('.craft-effort-slider input:not(:disabled)')`)
  await clickText('恢复默认推理等级')
  await waitFor(`document.querySelector('.craft-model-effort')?.textContent==='High'`)
  await waitFor(`!!document.querySelector('.craft-effort-slider input:not(:disabled)')`)
  // New panel uses the real model catalog and can return without changing model.
  await evaluate(`document.querySelector('.craft-reasoning-model').click()`)
  await waitFor(`!!document.querySelector('.craft-model-list [aria-checked="true"]')`)
  await capture('reasoning-model-list')
  await clickText('返回推理等级')
  for (const width of [1440, 640, 390]) {
    await call('Emulation.setDeviceMetricsOverride', { width, height: 900, deviceScaleFactor: 1, mobile: false })
    await delay(150)
    assert.equal(await evaluate(`(()=>{const e=document.querySelector('.craft-reasoning-popup'),r=e.getBoundingClientRect();return e.scrollWidth<=e.clientWidth+1&&r.left>=0&&r.right<=innerWidth&&r.top>=0&&r.bottom<=innerHeight})()`), true)
    await capture(`reasoning-slider-${width}`)
  }
  await key('keyDown', 'Escape', 27)
  await waitFor(`!document.querySelector('.craft-reasoning-popup')`)
  await call('Emulation.setDeviceMetricsOverride', { width: 1440, height: 1000, deviceScaleFactor: 1, mobile: false })
  await evaluate(`document.querySelector('button[title="DSH Craft UI"]').click()`)
  await clickText('推理等级控件: 滑动条')
  await clickText('完成')
  await waitFor(`!document.querySelector('.craft-model-trigger') && !!document.querySelector('button[aria-label^="选择模型"]')`)
  await call('Page.reload', { ignoreCache: true })
  await waitFor(`!!document.querySelector('button[aria-label^="选择模型"][aria-haspopup="menu"]')`)
  await evaluate(`document.querySelector('button[aria-label^="选择模型"]').click()`)
  await clickText('推理等级High')
  await waitFor(`document.querySelectorAll('[role="menuitemradio"]').length===4`)
  await capture('reasoning-legacy-menu')
  await key('keyDown', 'Escape', 27); await key('keyDown', 'Escape', 27)
  await evaluate(`document.querySelector('button[title="DSH Craft UI"]').click()`)
  await clickText('推理等级控件: 旧版菜单')
  await clickText('世界主题: 深板岩夜间')
  await clickText('完成')
  await waitFor(`!!document.querySelector('.craft-model-trigger')`)
  await evaluate(`document.querySelector('.craft-model-trigger').click()`)
  await waitFor(`!!document.querySelector('.craft-effort-slider input:not(:disabled)')`)
  await capture('reasoning-slider-day')
  assert.equal(await evaluate(`getComputedStyle(document.querySelector('.craft-effort-labels [aria-pressed="true"]')).backgroundColor`), 'rgb(233, 227, 204)', 'Day selection must not inherit a dark night-only background')
  await capture('reasoning-compact-day-detail', '.craft-reasoning-popup')
  // Return the isolated fixture's effort to its original value.
  await evaluate(`document.querySelectorAll('.craft-effort-labels button')[${Number(initial)}].click()`)
  await waitFor(`document.querySelector('.craft-effort-slider input')?.value===${JSON.stringify(initial)}`)
  assert.deepEqual(errors, [])
  console.log(`Reasoning integration passed: compact ${compact.width}x${compact.height}px popup, explicit model switch, real adapter levels, pointer + keyboard commit, Host persistence, default reset, responsive themes, legacy opt-out/persistence/restoration. No model prompts submitted.`)
})
