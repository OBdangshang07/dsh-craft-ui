import assert from 'node:assert/strict'
import { build } from 'esbuild'
import { resolve } from 'node:path'
import { withCanaryBrowser, delay } from './canary-browser.mjs'
import { readFile } from 'node:fs/promises'

const root = resolve(import.meta.dirname, '..'), log = process.argv[2]
if (!log) throw new Error('Pass the isolated canary startup log')
const result = await build({ entryPoints: [resolve(root, 'scripts/workbench-fixture.tsx')], bundle: true, write: false, format: 'iife', platform: 'browser', jsx: 'automatic', define: { 'process.env.NODE_ENV': '"production"' } })
await withCanaryBrowser(log, async b => {
  const { evaluate, waitFor, clickText, call, capture, errors } = b
  await call('Page.bringToFront')
  await evaluate(`([...document.querySelectorAll('button')].find(b=>b.textContent.trim()==='继续'))?.click()`)
  await delay(400)
  await evaluate(`{ const s=document.createElement('style');s.textContent=${JSON.stringify(await readFile(resolve(root, 'src/client/workbench.css'), 'utf8'))};document.head.append(s); }`)
  await evaluate(result.outputFiles[0].text)
  await waitFor(`document.querySelectorAll('.craft-map-preview img').length === 4`)
  await capture('workbench-gallery-night')
  await evaluate(`document.querySelector('.craft-map-preview').click()`)
  await waitFor(`!!document.querySelector('.craft-workbench [alt="H:/截图/建筑方案-1.png"]')`)
  assert.equal(await evaluate(`getComputedStyle(document.querySelector('.craft-image-canvas img')).imageRendering`), 'auto')
  const change = async (selector, value) => evaluate(`(() => {const el=document.querySelector(${JSON.stringify(selector)});const setter=Object.getOwnPropertyDescriptor(Object.getPrototypeOf(el),'value').set;setter.call(el,${JSON.stringify(value)});el.dispatchEvent(new Event('input',{bubbles:true}));el.dispatchEvent(new Event('change',{bubbles:true}));})()`)
  await change('.craft-region-fields input', '10')
  await change('.craft-annotation-controls textarea', '这里的窗户请向右移动，并保留屋顶。')
  await clickText('保存标注')
  await waitFor(`window.craftWorkbenchFixture.notes().entries.length===1`)
  await evaluate(`(() => { const original=HTMLAnchorElement.prototype.click;HTMLAnchorElement.prototype.click=function(){if(this.download==='craft-annotated-derived.png'){window.craftTestDownload={url:this.href,name:this.download};return}original.call(this)}; })()`)
  await clickText('导出标注 PNG')
  await waitFor(`!!window.craftTestDownload`)
  const exported = await evaluate(`(async()=>{const blob=await fetch(window.craftTestDownload.url).then(r=>r.blob());const bitmap=await createImageBitmap(blob);const result={type:blob.type,width:bitmap.width,height:bitmap.height,bytes:blob.size};bitmap.close();return result})()`)
  assert.equal(exported.type, 'image/png'); assert.equal(exported.width, 640); assert.equal(exported.height, 400); assert.ok(exported.bytes > 100)
  await clickText('将反馈加入草稿')
  assert.match(await evaluate(`document.querySelector('#fixture-draft').value`), /^保留我的现有输入 @file\n\n\[Image feedback/)
  assert.equal(await evaluate(`window.craftWorkbenchFixture.calls()`), 0)
  await capture('workbench-mark-night')
  await change('.craft-annotation-controls textarea', '尚未保存的修改')
  await clickText('关闭')
  await waitFor(`document.querySelector('[role="alert"]')?.textContent.includes('尚未保存')`)
  await clickText('返回保存')
  assert.equal(await evaluate(`document.querySelector('.craft-annotation-controls textarea').value`), '尚未保存的修改')
  await evaluate(`document.querySelector('.craft-workbench-header button').click()`)
  await clickText('放弃未保存更改')
  await clickText('打开图片工作台 / 对比')
  await change('.craft-workbench-toolbar select:nth-of-type(1)', '100')
  await evaluate(`(() => {const el=[...document.querySelectorAll('.craft-workbench-toolbar select')].find(e=>[...e.options].some(o=>o.value==='compare'));el.value='compare';el.dispatchEvent(new Event('change',{bubbles:true}));})()`)
  await waitFor(`document.querySelectorAll('.craft-image-viewport').length===2`)
  await capture('workbench-compare-night')
  await evaluate(`document.querySelector('.craft-workbench-header button').click()`)
  await clickText('打开会话书签')
  await clickText('收藏消息')
  await clickText('收藏摘录')
  await clickText('保存')
  await waitFor(`window.craftWorkbenchFixture.notes().entries.length===2`)
  await capture('workbench-book-night')
  await clickText('来源原文')
  await waitFor(`!!document.querySelector('.craft-notebook-source')`)
  await clickText('返回')
  await evaluate(`(() => {const entry=window.craftWorkbenchFixture.notes().entries.find(e=>e.kind!=='annotation');const backup={schema:1,sessionId:'fixture-session',entries:[{...entry,id:'imported-note'}]};const transfer=new DataTransfer();transfer.items.add(new File([JSON.stringify(backup)],'test-notebook.json',{type:'application/json'}));const input=document.querySelector('.craft-notebook-import input');input.files=transfer.files;input.dispatchEvent(new Event('change',{bubbles:true}));})()`)
  await waitFor(`!!document.querySelector('.craft-import-confirm')`)
  assert.equal(await evaluate(`window.craftWorkbenchFixture.notes().entries.length`), 2)
  await clickText('确认导入')
  await waitFor(`window.craftWorkbenchFixture.notes().entries.length===3`)
  await clickText('删除')
  await clickText('确认删除')
  await waitFor(`window.craftWorkbenchFixture.notes().entries.length===2`)
  for (const width of [1440, 1024, 640, 390]) {
    await call('Emulation.setDeviceMetricsOverride', { width, height: 900, deviceScaleFactor: 1, mobile: false })
    await delay(120)
    assert.equal(await evaluate(`(()=>{const e=document.querySelector('.craft-workbench');return e.scrollWidth>e.clientWidth+1})()`), false, `Dialog horizontal overflow at ${width}`)
    await capture(`workbench-book-${width}`)
  }
  await evaluate(`document.querySelector('.craft-workbench-header button').click()`)
  await evaluate(`window.craftWorkbenchFixture.setPreferences({theme:'craft-day'});document.body.dataset.craftTheme='craft-day'`)
  await clickText('打开图片工作台 / 对比')
  await capture('workbench-map-day-mobile')
  // Focus remains inside even when code tries to move it into the background.
  await evaluate(`document.querySelector('#fixture-draft').focus()`)
  assert.equal(await evaluate(`document.querySelector('.craft-workbench').contains(document.activeElement)`), true)
  await call('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 })
  await waitFor(`!document.querySelector('.craft-workbench')`)
  await evaluate(`window.craftWorkbenchFixture.setPreferences({imageJournal:false})`)
  assert.equal(await evaluate(`window.craftWorkbenchFixture.rows().includes('tool.call.toolview:read_image')`), false)
  assert.equal(await evaluate(`window.craftWorkbenchFixture.calls()`), 0)
  assert.deepEqual(errors, [])
  console.log('Workbench browser fixture passed: gallery, compare, annotations, derived PNG, unsaved-change guard, draft preservation, bookmarks/import/delete, focus, responsive sizes, opt-out; no model requests.')
})
