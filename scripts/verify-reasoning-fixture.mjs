import assert from 'node:assert/strict'
import { build } from 'esbuild'
import { withCanaryBrowser, delay } from './canary-browser.mjs'

const log = process.argv[2]
if (!log) throw new Error('Pass the isolated canary log')
const bundle = await build({ entryPoints: ['scripts/reasoning-fixture.tsx'], bundle: true, write: false, format: 'iife', platform: 'browser', jsx: 'automatic', define: { 'process.env.NODE_ENV': '"production"' } })
await withCanaryBrowser(log, async b => {
  const { evaluate, call, waitFor, clickText, capture, errors } = b
  await call('Page.bringToFront')
  await evaluate(bundle.outputFiles[0].text)
  await waitFor(`!!document.querySelector('#craft-reasoning-fixture button')`)
  const open = () => evaluate(`document.querySelector('#craft-reasoning-fixture button').click()`)
  await open()
  await waitFor(`document.querySelectorAll('.craft-effort-labels button').length===6`)
  for (const width of [1440, 390, 280]) {
    await call('Emulation.setDeviceMetricsOverride', { width, height: 900, deviceScaleFactor: 1, mobile: false })
    await delay(100)
    assert.equal(await evaluate(`(()=>{const e=document.querySelector('.craft-reasoning-popup');return e.scrollWidth<=e.clientWidth})()`), true)
    await capture(`reasoning-six-stops-${width}`)
  }
  // The visible Change action opens the catalog through keyboard activation.
  await evaluate(`document.querySelector('.craft-reasoning-model').focus()`)
  await call('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Enter', code: 'Enter', text: '\r', unmodifiedText: '\r', windowsVirtualKeyCode: 13 })
  await call('Input.dispatchKeyEvent', { type: 'keyUp', key: 'Enter', code: 'Enter', windowsVirtualKeyCode: 13 })
  await waitFor(`!!document.querySelector('.craft-model-list [aria-checked="true"]')`)
  await clickText('Synthetic model B')
  await waitFor(`window.craftReasoningFixture.state().current.model==='fixture-b' && !!document.querySelector('.craft-effort-slider')`)
  assert.equal(await evaluate(`document.querySelector('.craft-model-current').textContent`), 'Synthetic model B')
  assert.equal(await evaluate(`window.craftReasoningFixture.state().current.reasoningEffort`), 'high')
  await evaluate(`window.craftReasoningFixture.setCase('long')`)
  await waitFor(`document.querySelector('.craft-model-current')?.textContent.includes('Long')`)
  assert.equal(await evaluate(`(()=>{const panel=document.querySelector('.craft-reasoning-popup'),model=panel.querySelector('.craft-reasoning-model'),change=model.querySelector('.craft-model-change'),a=model.getBoundingClientRect(),b=change.getBoundingClientRect();return panel.scrollWidth<=panel.clientWidth && b.right<=a.right && change.scrollWidth<=change.clientWidth})()`), true, 'Long model names must not push the Change action out of view')
  await evaluate(`window.craftReasoningFixture.setCase('six')`)
  await evaluate(`window.craftReasoningFixture.failNext()`)
  await clickText('LOW')
  await waitFor(`document.querySelector('.craft-reasoning-status')?.textContent.includes('Simulated')`)
  assert.equal(await evaluate(`window.craftReasoningFixture.state().current.reasoningEffort`), 'high')
  assert.equal(await evaluate(`document.querySelector('.craft-effort-slider input').value`), '3')
  await clickText('LOW')
  await waitFor(`window.craftReasoningFixture.state().current.reasoningEffort==='low'`)
  await waitFor(`!!document.querySelector('.craft-effort-slider input:not(:disabled)')`)
  const calls = await evaluate(`window.craftReasoningFixture.calls().length`)
  await evaluate(`document.querySelector('.craft-effort-slider input').focus()`)
  await call('Input.dispatchKeyEvent', { type: 'keyDown', key: 'End', code: 'End', windowsVirtualKeyCode: 35 })
  await call('Input.dispatchKeyEvent', { type: 'keyDown', key: 'Escape', code: 'Escape', windowsVirtualKeyCode: 27 })
  await waitFor(`!document.querySelector('.craft-reasoning-popup')`)
  assert.equal(await evaluate(`window.craftReasoningFixture.calls().length`), calls)
  assert.equal(await evaluate(`window.craftReasoningFixture.state().current.reasoningEffort`), 'low')
  await open()
  await evaluate(`window.craftReasoningFixture.setCase('unknown')`)
  await waitFor(`document.querySelector('.craft-effort-slider')?.hasAttribute('data-unmapped')`)
  assert.match(await evaluate(`document.querySelector('.craft-reasoning-heading').textContent`), /unknown/)
  await evaluate(`window.craftReasoningFixture.setCase('single')`)
  await waitFor(`document.querySelector('.craft-effort-slider input')?.disabled===true`)
  await evaluate(`window.craftReasoningFixture.setCase('none')`)
  await waitFor(`!document.querySelector('.craft-effort-slider')`)
  assert.equal(await evaluate(`window.craftReasoningFixture.calls().length`), calls)
  assert.deepEqual(errors, [])
  console.log('Reasoning fixtures passed: keyboard model switching, long-name action visibility, six/single/no/unknown levels, failed-write rollback, retry, Escape cancellation, 280/390/1440 widths. No network selections.')
})
